"""
Qiangli Q2.5 Pro (128x64, 1/32 Scan) Image Converter for ESP32-S3
Converts any 128x64 image (PNG, JPG, BMP) into an optimized C++ array for the driver.
"""

import sys
import os
import cv2
import numpy as np

def convert_image(image_path, output_header="splash_data.h"):
    if not os.path.exists(image_path):
        print(f"Error: File '{image_path}' not found!")
        return False

    img = cv2.imread(image_path)
    if img is None:
        print(f"Error: Could not load image '{image_path}'!")
        return False

    # Resize to exact 128x64 if necessary
    h, w, _ = img.shape
    if w != 128 or h != 64:
        print(f"Warning: Image size is {w}x{h}. Resizing to 128x64...")
        img = cv2.resize(img, (128, 64), interpolation=cv2.INTER_AREA)

    # Threshold color channels (BGR)
    B = img[:, :, 0] > 70
    G = img[:, :, 1] > 70
    R = img[:, :, 2] > 70

    # Hardware calibrated pin mapping for ESP32-S3:
    # TOP HALF (Y = 0..31):
    #   PIN_R1 = GPIO 4
    #   PIN_G1 = GPIO 5
    #   PIN_B1 = GPIO 6
    # BOTTOM HALF (Y = 32..63):
    #   PIN_R2 = GPIO 7
    #   PIN_G2 = GPIO 15
    #   PIN_B2 = GPIO 16

    masks = np.zeros((32, 16, 8), dtype=np.uint32)

    for line in range(32):
        y_top = line
        y_bot = line + 32
        for col in range(16):
            for ch in range(8):
                x = (ch * 16) + col

                # Top half subpixels
                m_top = 0
                if R[y_top, x]: m_top |= (1 << 4)
                if G[y_top, x]: m_top |= (1 << 5)
                if B[y_top, x]: m_top |= (1 << 6)

                # Bottom half subpixels
                m_bot = 0
                if R[y_bot, x]: m_bot |= (1 << 7)
                if G[y_bot, x]: m_bot |= (1 << 15)
                if B[y_bot, x]: m_bot |= (1 << 16)

                masks[line, col, ch] = m_top | m_bot

    with open(output_header, "w", encoding="utf-8") as f:
        f.write("// ============================================================================\n")
        f.write("// Qiangli Q2.5 Pro (128x64) Matrix Framebuffer Data\n")
        f.write("// Auto-generated by image_to_matrix.py\n")
        f.write("// ============================================================================\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("const uint32_t SPLASH_FRAME_MASKS[32][16][8] PROGMEM = {\n")
        for line in range(32):
            f.write(f"  {{ // Scan Line {line} (Row {line} & Row {line + 32})\n")
            for col in range(16):
                f.write("    { " + ", ".join(f"0x{m:08X}UL" for m in masks[line, col]) + " },\n")
            f.write("  },\n")
        f.write("};\n")

    print(f"Success! Generated '{output_header}' from '{image_path}' ({os.path.getsize(output_header)} bytes).")
    return True

if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "splash_128x64.png"
    dst = sys.argv[2] if len(sys.argv) > 2 else "splash_data.h"
    convert_image(src, dst)
